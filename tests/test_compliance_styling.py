# ── 2. apply_compliance_to_header 单元 ──────────────────────────

class TestApplyComplianceToHeader:

    def test_allow_keeps_open_source_font(self, tmp_path):
        from font_intel.integration import FontComplianceConfig, apply_compliance_to_header
        db_path = _seed_db_file(tmp_path / "fonts.db")
        cfg = FontComplianceConfig(enabled=True, db_path=db_path)
        new_header, decisions = apply_compliance_to_header(
            GOLDEN_DEFAULT_HEADER, cfg)
        # 开源字体放行：原名保留，头部仅有的思源黑体 Style 行不动。
        assert "Style: Default,思源黑体 CN,43," in new_header
        by_font = {d["font_name"]: d for d in decisions}
        assert by_font["思源黑体 CN"]["action"] == "allow"
        assert by_font["思源黑体 CN"]["license_category"] == "open_source"
        assert by_font["思源黑体 CN"]["final_font"] == "思源黑体 CN"
        assert by_font["思源黑体 CN"]["granted"] is False

    def test_prompt_non_interactive_keeps_and_records(self, tmp_path):
        from font_intel.integration import FontComplianceConfig, apply_compliance_to_header
        db_path = _seed_db_file(tmp_path / "fonts.db")
        cfg = FontComplianceConfig(
            enabled=True, db_path=db_path)  # interactive 缺省 False
        new_header, decisions = apply_compliance_to_header(
            GOLDEN_DEFAULT_HEADER, cfg)
        # 商用需授权：非交互模式降级为保留原名 + 记录决策，绝不阻塞出片。
        assert "Style: KO,Malgun Gothic,43," in new_header
        by_font = {d["font_name"]: d for d in decisions}
        d = by_font["Malgun Gothic"]
        assert d["action"] == "prompt"
        assert d["license_category"] == "commercial_paid"
        assert d["final_font"] == "Malgun Gothic"
        assert "非交互" in d["reason"]
        assert d["official_url"] == "https://www.fonts.go.kr/malgun"
        assert d["styles"] == ["KO"]

    def test_replace_auto_replaces_only_target_style(self, tmp_path):
        from font_intel.integration import apply_compliance_to_header
        db_path = _seed_db_file(tmp_path / "fonts.db")
        cfg = _replace_auto_config(db_path, confidence=0.9)
        new_header, decisions = apply_compliance_to_header(
            GOLDEN_DEFAULT_HEADER, cfg)
        # KO 行字体被替换为替代字体链第一项。
        assert "Style: KO,思源黑体 CN,43," in new_header
        assert "Style: KO,Malgun Gothic" not in new_header
        # 其余 Style 行与 Format 行逐字节不动。
        assert "Style: JP,源ノ角ゴシック JP,43," in new_header
        assert "Style: RU,Arial,43," in new_header
        assert "Style: Default,思源黑体 CN,43," in new_header
        assert ("Format: Name, Fontname, Fontsize, PrimaryColour,"
                " SecondaryColour") in new_header
        by_font = {d["font_name"]: d for d in decisions}
        d = by_font["Malgun Gothic"]
        assert d["action"] == "replace_auto"
        assert d["final_font"] == "思源黑体 CN"
        assert d["replaced"] is True
        assert d["styles"] == ["KO"]

    def test_replace_auto_low_confidence_degrades_to_keep(self, tmp_path):
        from font_intel.integration import apply_compliance_to_header
        db_path = _seed_db_file(tmp_path / "fonts.db")
        cfg = _replace_auto_config(db_path, confidence=0.6)
        new_header, decisions = apply_compliance_to_header(
            GOLDEN_DEFAULT_HEADER, cfg)
        # 置信度不达门槛 → decide 内部降级 prompt → 保留原名。
        assert "Style: KO,Malgun Gothic,43," in new_header
        by_font = {d["font_name"]: d for d in decisions}
        d = by_font["Malgun Gothic"]
        assert d["action"] == "prompt"
        assert d["final_font"] == "Malgun Gothic"
        assert d["replaced"] is False

    def test_template_mode_collects_without_modifying(self, tmp_path):
        from font_intel.integration import FontComplianceConfig, apply_compliance_to_header
        db_path = _seed_db_file(tmp_path / "fonts.db")
        cfg = FontComplianceConfig(enabled=True, db_path=db_path)
        new_header, decisions = apply_compliance_to_header(
            GOLDEN_DEFAULT_HEADER, cfg, template_mode=True)
        # 用户模板不重写：逐字节原样返回，仅收集决策。
        assert new_header == GOLDEN_DEFAULT_HEADER
        assert {d["font_name"] for d in decisions} >= {"Malgun Gothic",
                                                       "思源黑体 CN"}

    def test_decisions_deduped_by_font_name(self, tmp_path):
        from font_intel.integration import FontComplianceConfig, apply_compliance_to_header
        db_path = _seed_db_file(tmp_path / "fonts.db")
        cfg = FontComplianceConfig(enabled=True, db_path=db_path)
        _header, decisions = apply_compliance_to_header(
            GOLDEN_DEFAULT_HEADER, cfg)
        # 去重：思源黑体 CN 占 4 条 Style 行只出 1 条决策，多个 style 名
        # 记录在其下；总决策数 = 去重字体数（4）。
        assert len(decisions) == 4
        by_font = {d["font_name"]: d for d in decisions}
        assert by_font["思源黑体 CN"]["styles"] == ["Default", "CH", "Top",
                                                    "Scene"]
        assert by_font["思源黑体 CN"]["style"] == "Default"

    def test_none_or_disabled_config_is_noop(self):
        from font_intel.integration import FontComplianceConfig, apply_compliance_to_header
        header, decisions = apply_compliance_to_header(
            GOLDEN_DEFAULT_HEADER, None)
        assert header == GOLDEN_DEFAULT_HEADER
        assert decisions == []
        cfg = FontComplianceConfig(enabled=False)
        header, decisions = apply_compliance_to_header(
            GOLDEN_DEFAULT_HEADER, cfg)
        assert header == GOLDEN_DEFAULT_HEADER
        assert decisions == []


