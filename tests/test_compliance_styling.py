class TestWriteComplianceReport:

    def _decisions(self, tmp_path):
        from font_intel.integration import FontComplianceConfig, apply_compliance_to_header
        db_path = _seed_db_file(tmp_path / "fonts.db")
        cfg = FontComplianceConfig(enabled=True, db_path=db_path)
        _header, decisions = apply_compliance_to_header(
            GOLDEN_DEFAULT_HEADER, cfg)
        assert decisions
        return decisions

    def test_report_files_naming_and_content(self, tmp_path):
        from font_intel.integration import write_compliance_report
        decisions = self._decisions(tmp_path)
        ass_path = tmp_path / "movie.ass"
        md_path, json_path = write_compliance_report(
            decisions, ass_path, meta={"video": "movie.mp4"})
        # 与 ASS 同目录、命名 <stem>_compliance_report.md/.json。
        assert md_path == tmp_path / "movie_compliance_report.md"
        assert json_path == tmp_path / "movie_compliance_report.json"
        assert md_path.exists() and json_path.exists()

        md_text = md_path.read_text(encoding="utf-8")
        assert DISCLAIMER in md_text  # 免责声明原句
        assert "Malgun Gothic" in md_text
        assert "思源黑体 CN" in md_text
        assert "commercial_paid" in md_text
        assert "prompt" in md_text
        assert "https://www.fonts.go.kr/malgun" in md_text  # 经消毒的官方链接

        payload = json.loads(json_path.read_text(encoding="utf-8"))
        assert payload["disclaimer"] == DISCLAIMER
        assert payload["meta"] == {"video": "movie.mp4"}
        assert payload["ass_path"] == str(ass_path)
        assert payload["decisions"]
        for entry in payload["decisions"]:
            for key in ("style", "styles", "font_name", "final_font",
                        "action", "license_category", "reason",
                        "official_url"):
                assert key in entry

    def test_empty_decisions_writes_no_files(self, tmp_path):
        from font_intel.integration import write_compliance_report
        result = write_compliance_report([], tmp_path / "x.ass")
        assert result == (None, None)
        assert list(tmp_path.glob("*")) == []


