# ── 构造辅助 ─────────────────────────────────────────────────────

def _make_optimizer(tmp_path, **kw) -> OCRToASSOptimizer:
    return OCRToASSOptimizer(
        video_path=str(tmp_path / "in.mp4"),
        output_path=str(tmp_path / "out.ass"),
        fps=25.0,
        width=1280,
        height=720,
        **kw,
    )


def _make_item(frame_num, text, box):
    poly = [[box[0], box[1]], [box[2], box[1]], [box[2], box[3]], [box[0], box[3]]]
    data = {
        "dt_polys": [poly],
        "rec_polys": [poly],
        "rec_texts": [text],
        "rec_scores": [0.95],
        "rec_boxes": [list(box)],
    }
    return (data, frame_num, "roi_0", frame_num / 25.0)


def _items():
    # 底部区域 → BOTTOM 组，产出对白事件（头部样式行与事件无关）。
    return [_make_item(f, "学成归来", (100, 600, 500, 650)) for f in range(10, 21)]


def _seed_db_file(path) -> str:
    """种子库：思源黑体 CN=open_source，Malgun Gothic=commercial_paid。"""
    db = FontsDB(str(path))
    db.import_seed([
        {"table": "fonts", "canonical_name": "思源黑体 CN",
         "license_category": "open_source",
         "official_url": "https://github.com/adobe-fonts/source-han-sans",
         "source": "test-seed"},
        {"table": "fonts", "canonical_name": "Malgun Gothic",
         "license_category": "commercial_paid",
         "official_url": "https://www.fonts.go.kr/malgun",
         "source": "test-seed"},
    ])
    db.close()
    return str(path)


def _no_report_files(tmp_path):
    return sorted(p.name for p in tmp_path.glob("*_compliance_report.*"))


def _replace_auto_config(db_path: str, confidence=0.9):
    from font_intel.compliance import ComplianceRules
    from font_intel.integration import FontComplianceConfig

    rules = ComplianceRules()
    rules.set_override("commercial_paid", "personal", "replace_auto")
    return FontComplianceConfig(
        enabled=True,
        scene="personal",
        rules=rules,
        db_path=db_path,
        confidence=confidence,
        alternatives_provider=lambda name: ["思源黑体 CN"],
    )


